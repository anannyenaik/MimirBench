def load_task_scores(results_path: str | Path) -> list[TaskScore]:
    """Load per-task scores from a saved ``results.jsonl`` (no model is run)."""
    records = load_records_jsonl(Path(results_path))
    scores: list[TaskScore] = []
    for record in records:
        scores.append(
            TaskScore(
                environment=record.environment,
                task_id=record.task_id,
                seed=int(record.seed),
                score=float(record.grader_result.score),
                passed=bool(record.grader_result.passed),
                parse_failed=record.parsed_response is None,
                risk_violation=is_risk_violation(record.grader_result),
                latency_ms=record.latency_ms,
            )
        )
    return scores


def _proportion_ci(flags: Sequence[bool], *, seed: int) -> BootstrapResult:
    return bootstrap_ci(
        [1.0 if flag else 0.0 for flag in flags],
        n_resamples=_N_RESAMPLES,
        confidence=0.95,
        seed=seed,
    )


def _percentile(values: Sequence[float], q: float) -> float | None:
    finite = [v for v in values if v is not None]
    if not finite:
        return None
    return float(np.percentile(np.asarray(finite, dtype=np.float64), q))


def summarise_row(
    row: CanonicalRow,
    scores: Sequence[TaskScore],
    *,
    cost_usd: float | None = None,
    seed: int = _BOOTSTRAP_SEED,
) -> RowStatistics:
    """Compute bootstrap CIs and descriptive stats for one canonical row."""
    if not scores:
        raise ValueError(f"no task scores for row {row.key!r}.")
    latencies = [s.latency_ms for s in scores if s.latency_ms is not None]
    return RowStatistics(
        key=row.key,
        display=row.display,
        track=row.track,
        n=len(scores),
        mean_score=bootstrap_ci(
            [s.score for s in scores], n_resamples=_N_RESAMPLES, confidence=0.95, seed=seed
        ),
        pass_rate=_proportion_ci([s.passed for s in scores], seed=seed + 1),
        parse_failure_rate=_proportion_ci([s.parse_failed for s in scores], seed=seed + 2),
        risk_violation_rate=_proportion_ci([s.risk_violation for s in scores], seed=seed + 3),
        latency_p50_ms=_percentile(latencies, 50.0),
        latency_p95_ms=_percentile(latencies, 95.0),
        cost_usd=cost_usd,
        caveat=row.caveat,
    )


def paired_delta(
    baseline_key: str,
    candidate_key: str,
    baseline_scores: Sequence[TaskScore],
    candidate_scores: Sequence[TaskScore],
    *,
    seed: int = _BOOTSTRAP_SEED,
) -> PairedDelta:
    """Paired mean-score delta over aligned ``(env, task_id, seed)`` keys.

    Alignment requires the *same* task identity in both rows. If fewer than two
    keys align, the result is marked unpaired (descriptive only).
    """
    base_by_key = {(s.environment, s.task_id, s.seed): s.score for s in baseline_scores}
    cand_by_key = {(s.environment, s.task_id, s.seed): s.score for s in candidate_scores}
    shared = sorted(set(base_by_key) & set(cand_by_key))
    deltas = [cand_by_key[k] - base_by_key[k] for k in shared]
    if len(deltas) < 2:
        return PairedDelta(
            baseline=baseline_key,
            candidate=candidate_key,
            n_aligned=len(deltas),
            n_baseline=len(baseline_scores),
            n_candidate=len(candidate_scores),
            mean_delta=float(np.mean(deltas)) if deltas else None,
            delta_ci=None,
            aligned=False,
            note="unpaired descriptive comparison (task IDs/seeds do not align)",
        )
    ci = bootstrap_ci(deltas, n_resamples=_N_RESAMPLES, confidence=0.95, seed=seed)
    return PairedDelta(
        baseline=baseline_key,
        candidate=candidate_key,
        n_aligned=len(deltas),
        n_baseline=len(baseline_scores),
        n_candidate=len(candidate_scores),
        mean_delta=float(np.mean(deltas)),
        delta_ci=ci,
        aligned=True,
        note="paired over aligned task IDs/seeds",
    )


def _load_cost(base_dir: Path, row: CanonicalRow) -> float | None:
    summary_path = base_dir / row.run_dir / "leaderboard_summary.json"
    if not summary_path.exists():
        return None
    data = json.loads(summary_path.read_text(encoding="utf-8"))
    leaderboard = data.get("leaderboard")
    if not isinstance(leaderboard, list):
        return None
    for entry in leaderboard:
        if isinstance(entry, dict) and entry.get("model") == row.model_dir:
            cost = entry.get("estimated_cost_usd")
            return float(cost) if isinstance(cost, (int, float)) else None
    return None


def _results_path(base_dir: Path, row: CanonicalRow) -> Path:
    return base_dir / row.run_dir / "models" / row.model_dir / "agents" / row.agent / "results.jsonl"


def _fmt(value: float | None, digits: int = 4) -> str:
    if value is None:
        return "n/a"
    return f"{value:.{digits}f}"


def _ci(result: BootstrapResult) -> str:
    return f"[{result.low:.4f}, {result.high:.4f}]"


def build_statistical_validity_markdown(
    base_dir: str | Path = Path("reports") / "runs" / "leaderboard",
    *,
    rows: Sequence[CanonicalRow] = CANONICAL_ROWS,
    seed: int = _BOOTSTRAP_SEED,
) -> str:
    """Render the canonical CI table and paired-delta tables from saved artefacts.

    Rows whose artefacts are missing are listed explicitly as missing rather than
    skipped silently. No model is ever run.
    """
    base = Path(base_dir)
    loaded: dict[str, list[TaskScore]] = {}
    stats: list[RowStatistics] = []
    missing: list[CanonicalRow] = []
    for row in rows:
        path = _results_path(base, row)
        if not path.exists():
            missing.append(row)
            continue
        scores = load_task_scores(path)
        loaded[row.key] = scores
        stats.append(summarise_row(row, scores, cost_usd=_load_cost(base, row), seed=seed))

    lines: list[str] = [
        "# Statistical validity over existing artefacts",
        "",
        "Generated by `mimirbench statistical-validity` from saved real-model "
        "`results.jsonl` files only. **No model is run to produce this file.** Every "
        "interval is a percentile bootstrap "
        f"(n_resamples={_N_RESAMPLES}, 95%, seed={seed}) over the saved synthetic "
        "sample — a pilot CI quantifying sampling noise on *this* sample, not a "
        "population-level benchmark claim.",
        "",
        "Tracks follow [BENCHMARK_PROTOCOL.md](../../../BENCHMARK_PROTOCOL.md): "
        "`strict-track clean` rows share the 512-token output budget and decoding "
        "protocol; `best-valid clean` rows use each provider's documented minimum "
        "settings to emit valid JSON (not identical-decoding); `protocol-limited` "
        "rows are retained as documented output-budget/protocol findings, not "
        "capability scores.",
        "",
        "## Canonical per-row table (95% bootstrap CIs)",
        "",
        "| Model | Track | n | Mean | 95% CI | Pass | Pass CI | Parse fail | "
        "Parse-fail CI | Risk viol. | Risk CI | Cost (USD) | p50/p95 latency (ms) | Caveat |",
        "| --- | --- | ---: | ---: | --- | ---: | --- | ---: | --- | ---: | --- | "
        "---: | ---: | --- |",
    ]
    for stat in stats:
        latency = (
            f"{stat.latency_p50_ms:.0f} / {stat.latency_p95_ms:.0f}"
            if stat.latency_p50_ms is not None and stat.latency_p95_ms is not None
            else "n/a"
        )
        cost = f"${stat.cost_usd:.4f}" if stat.cost_usd is not None else "n/a"
        lines.append(
            f"| {stat.display} | {stat.track} | {stat.n} | "
            f"{_fmt(stat.mean_score.mean)} | {_ci(stat.mean_score)} | "
            f"{_fmt(stat.pass_rate.mean)} | {_ci(stat.pass_rate)} | "
            f"{_fmt(stat.parse_failure_rate.mean)} | {_ci(stat.parse_failure_rate)} | "
            f"{_fmt(stat.risk_violation_rate.mean)} | {_ci(stat.risk_violation_rate)} | "
            f"{cost} | {latency} | {stat.caveat} |"
        )

    lines.extend(["", "## Paired model deltas (candidate minus baseline)", ""])
    lines.append(
        "Deltas are computed only over tasks whose `(environment, task_id, seed)` "
        "align in both rows. Rows that do not align are reported as unpaired "
        "descriptive comparisons. A 95% bootstrap CI that excludes 0 indicates the "
        "paired difference is unlikely to be sampling noise *on this sample*; it is "
        "not a population-level significance claim."
    )
    lines.append("")
    lines.append(
        "| Baseline | Candidate | Aligned n | Mean Δ score | 95% CI | Excludes 0? | Note |"
    )
    lines.append("| --- | --- | ---: | ---: | --- | :---: | --- |")
    for baseline_key, candidate_key in _PAIRED_COMPARISONS:
        if baseline_key not in loaded or candidate_key not in loaded:
            continue
        delta = paired_delta(
            baseline_key,
            candidate_key,
            loaded[baseline_key],
            loaded[candidate_key],
            seed=seed,
        )
        base_display = _display_for(rows, baseline_key)
        cand_display = _display_for(rows, candidate_key)
        if delta.aligned and delta.delta_ci is not None:
            excludes = "yes" if (delta.delta_ci.low > 0 or delta.delta_ci.high < 0) else "no"
            lines.append(
                f"| {base_display} | {cand_display} | {delta.n_aligned} | "
                f"{_fmt(delta.mean_delta)} | {_ci(delta.delta_ci)} | {excludes} | {delta.note} |"
            )
        else:
            lines.append(
                f"| {base_display} | {cand_display} | {delta.n_aligned} | "
                f"{_fmt(delta.mean_delta)} | n/a | n/a | {delta.note} |"
            )

    if missing:
        lines.extend(["", "## Missing artefacts (not summarised)", ""])
        for row in missing:
            lines.append(f"- `{row.display}` — expected `{_results_path(base, row)}` (not found).")

    lines.extend(
        [
            "",
            "## Scope and Limitations",
            "",
            "- Single seed/schedule: every row uses one task schedule, so these CIs "
            "capture resampling noise over that fixed sample, not seed-to-seed "
            "variation.",
            "- Synthetic task distribution: tasks are deterministic synthetic "
            "environments, so the CIs do not generalise to real-world or live tasks.",
            "- Cross-provider deltas use each provider's documented clean protocol "
            "(different output budgets/decoding); they are not identical-decoding "
            "comparisons.",
            "- `protocol-limited` rows are included for completeness but reflect "
            "output-budget/protocol behaviour, not capability.",
            "- No broad provider- or model-superiority claim and no trading-usefulness "
            "claim is made.",
            "",
        ]
    )
    return "\n".join(lines)


def _display_for(rows: Sequence[CanonicalRow], key: str) -> str:
    for row in rows:
        if row.key == key:
            return row.display
    return key


def write_statistical_validity_report(
    base_dir: str | Path = Path("reports") / "runs" / "leaderboard",
    *,
    output_path: str | Path | None = None,
    rows: Sequence[CanonicalRow] = CANONICAL_ROWS,
    seed: int = _BOOTSTRAP_SEED,
) -> Path:
    """Write the statistical-validity markdown report and return its path."""
    base = Path(base_dir)
    out = (
        Path(output_path)
        if output_path is not None
        else base / "statistical_validity_existing_artifacts.md"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        build_statistical_validity_markdown(base, rows=rows, seed=seed), encoding="utf-8"
    )
    return out
