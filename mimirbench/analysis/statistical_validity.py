"""Statistical validity tables over *saved* real-model artefacts only.

This module never runs a model. It reads per-task ``results.jsonl`` files that
were already generated by the leaderboard pipeline and attaches explicit
uncertainty to the headline numbers:

* mean-score 95% bootstrap CI,
* pass-rate, parse-failure-rate, and risk-violation-rate CIs (proportions),
* paired model deltas where ``(environment, task_id, seed)`` actually align,
* per-row n and latency percentiles.

The intervals are pilot CIs over the saved synthetic sample, not population-level
benchmark claims. A single seed/schedule and a narrow synthetic task distribution
mean these quantify sampling noise on *this* sample only.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from mimirbench.evals.bootstrap import BootstrapResult, bootstrap_ci
from mimirbench.evals.scoring import is_risk_violation
from mimirbench.evals.writers import load_records_jsonl

